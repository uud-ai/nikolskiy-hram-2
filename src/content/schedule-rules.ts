// Правила расписания богослужений храма. Расписание на сайте строится по ним
// автоматически на любой срок вперёд (src/lib/schedule.ts) — вручную заполнять
// даты не нужно. Даты Пасхи и связанных с ней праздников вычисляются сами.
//
// Общее правило прихода:
//  - суббота — Таинство Крещения в 11:00;
//  - воскресенье — Божественная литургия в 10:00 и беседа перед Крещением в 12:00;
//  - Литургия в 10:00 также в двунадесятые и великие праздники и в престольные
//    дни (22 мая и 19 декабря); если праздник в субботу — Литургия в 10:00 и
//    Крещение в 11:00;
//  - Пасха — богослужение в 23:30 накануне (в Великую субботу);
//  - Рождество Христово — Литургия в 10:00.
//
// Разовые изменения (распоряжение настоятеля, отмена, перенос, дополнительная
// служба) — в списке scheduleExceptions в конце файла.

