export interface ScheduleException {
  /** Новый список служб на этот день (заменяет рассчитанный). Пустой список — служб нет. */
  events?: ScheduleEvent[]
  /** Новое название дня (заменяет рассчитанное). */
  title?: string
  /** Пояснение для себя, на сайте не показывается. */
  note?: string
}

/**
 * Разовые изменения расписания. Ключ — дата ГГГГ-ММ-ДД.
 *
 * Примеры:
 *   "2027-03-14": { events: [] },                                    // служб не будет
 *   "2027-03-20": { events: [LITURGY, BAPTISM] },                    // добавить Литургию к Крещению
 *   "2027-03-21": { events: [{ time: "09:00", name: LITURGY.name }] } // Литургия в 9:00
 *   "2027-04-10": { events: [{ time: "17:00", name: "Всенощное бдение" }], title: "Канун праздника" },
 *
 * Прошедшие даты можно не удалять — они на сайте не показываются.
 */
